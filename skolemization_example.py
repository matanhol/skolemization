def visible_variable_name(name):
    """
    Hide internal standardized variable names.

    Examples:

        __v230_x -> x
        __v17_y  -> y
        __v3_z   -> z

    Ordinary variable names remain unchanged.
    """

    match = re.match(
        r"^__v\d+_(.+)$",
        name
    )

    if match:
        return match.group(1)

    return name


