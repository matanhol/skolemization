# RESOLUTION SEARCH
# ================================================================

def run_resolution_search(
    starting_kb,
    title="Resolution"
):

    kb = [
        list(clause)
        for clause
        in starting_kb
    ]

    # Remember every clause ever produced,
    # even if later removed as redundant.
    ever_seen = {
        canonical_clause(
            clause
        )
        for clause
        in kb
    }

    print(
        "\n"
        + "=" * 70
    )

    print(title)

    print(
        "=" * 70
    )

    show_kb(
        kb,
        "KB בתחילת החיפוש"
    )

    for step in range(
        1,
        MAX_RESOLUTION_STEPS
        +
        1
    ):

        candidates = []

        # --------------------------------------------------------
        # Find all NEW possible resolutions
        # --------------------------------------------------------

        for i in range(
            len(kb)
        ):

            for j in range(
                i + 1,
                len(kb)
            ):

                possibilities = (
                    resolve_two_clauses(
                        kb[i],
                        kb[j]
                    )
                )

                for (
                    lit1,
                    lit2,
                    substitution,
                    resolvent
                ) in possibilities:

                    key = (
                        canonical_clause(
                            resolvent
                        )
                    )

                    if key in ever_seen:
                        continue

                    candidates.append(
                        (
                            i,
                            j,
                            lit1,
                            lit2,
                            substitution,
                            resolvent
                        )
                    )

        # --------------------------------------------------------
        # Saturation
        # --------------------------------------------------------

        if not candidates:

            print(
                "\n"
                + "#" * 70
            )

            print(
                "SATURATED_NO_CONTRADICTION"
            )

            print(
                "#" * 70
            )

            print(
                "\nאין resolvent חדש "
                "שאפשר להוסיף."
            )

            print(
                "לא נמצאה הפסוקית הריקה □."
            )

            return (
                "SATURATED_NO_CONTRADICTION",
                kb
            )

        # --------------------------------------------------------
        # Choose candidate
        # --------------------------------------------------------

        if (
            STRATEGY
            ==
            "random"
        ):

            chosen = (
                random.choice(
                    candidates
                )
            )

        else:

            chosen = min(
                candidates,
                key=lambda item: (
                    len(
                        item[5]
                    ),
                    len(
                        kb[
                            item[0]
                        ]
                    )
                    +
                    len(
                        kb[
                            item[1]
                        ]
                    )
                )
            )

        (
            i,
            j,
            lit1,
            lit2,
            substitution,
            resolvent
        ) = chosen

        parent1 = list(
            kb[i]
        )

        parent2 = list(
            kb[j]
        )

        # --------------------------------------------------------
        # Explain step
        # --------------------------------------------------------

        print(
            "\n"
            + "=" * 70
        )

        print(
            f"Resolution step {step}"
        )

        print(
            "=" * 70
        )

        print(
            "\nבוחרים:"
        )

        print(
            f"\nC{i+1}: "
            f"{clause_str(parent1)}"
        )

        print(
            f"C{j+1}: "
            f"{clause_str(parent2)}"
        )

        print(
            "\nהליטרלים שניתן להצליב:"
        )

        # Important:
        # Term.__str__ hides __vXXX_ names here.
        print(
            f"    {lit1}"
        )

        print(
            f"    {lit2}"
        )

        substitutions = (
            meaningful_substitutions(
                substitution
            )
        )

        print(
            "\nההצבה הדרושה:"
        )

        if substitutions:

            for (
                variable,
                value
            ) in substitutions:

                print(
                    f"    {variable} := {value}"
                )

        else:

            print(
                "    אין צורך בהצבה ממשית."
            )

        # Show instantiated literals
        instantiated1 = (
            apply_substitution_literal(
                lit1,
                substitution
            )
        )

        instantiated2 = (
            apply_substitution_literal(
                lit2,
                substitution
            )
        )

        print(
            "\nלאחר ההצבה:"
        )

        print(
            f"    {instantiated1}"
        )

        print(
            f"    {instantiated2}"
        )

        print(
            "\nהליטרלים זהים פרט לשלילה, "
            "ולכן מבטלים אותם."
        )

        print(
            "\nמתקבל:"
        )

        print(
            f"    {clause_str(resolvent)}"
        )

        ever_seen.add(
            canonical_clause(
                resolvent
            )
        )

        # --------------------------------------------------------
        # CONTRADICTION
        # --------------------------------------------------------

        if len(
            resolvent
        ) == 0:

            kb.append(
                resolvent
            )

            show_kb(
                kb,
                "KB הסופי"
            )

            print(
                "\n"
                + "#" * 70
            )

            print(
                "PROVED"
            )

            print(
                "#" * 70
            )

            print(
                "\nהתקבלה הפסוקית הריקה:"
            )

            print(
                "\n                  □"
            )

            print(
                "\nנמצאה סתירה."
            )

            print(
                "ההנחות יחד עם שלילת המסקנה "
                "אינן יכולות להיות אמיתיות יחד."
            )

            print(
                "\nלכן המסקנה נובעת מן ההנחות."
            )

            return (
                "PROVED",
                kb
            )

        # --------------------------------------------------------
        # Check ONLY current parents for redundancy
        # --------------------------------------------------------

        kb = (
            remove_redundant_parents(
                kb,
                i,
                j,
                resolvent
            )
        )

        # --------------------------------------------------------
        # Add resolvent
        # --------------------------------------------------------

        print(
            "\nמוסיפים את ה-resolvent ל-KB:"
        )

        print(
            f"    {clause_str(resolvent)}"
        )

        kb.append(
            resolvent
        )

        if (
            SHOW_FULL_KB_EACH_STEP
        ):

            show_kb(
                kb,
                "KB בסוף הצעד"
            )

    # ------------------------------------------------------------
    # Search limit
    # ------------------------------------------------------------

    print(
        "\n"
        + "#" * 70
    )

    print(
        "UNKNOWN"
    )

    print(
        "#" * 70
    )

    print(
        f"\nהגענו ל-"
        f"{MAX_RESOLUTION_STEPS} "
        "צעדי Resolution."
    )

    print(
        "לא נמצאה סתירה, "
        "אבל החיפוש עדיין לא מוצה."
    )

    return (
        "UNKNOWN",
        kb
    )


