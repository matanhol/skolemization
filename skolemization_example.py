class SkolemNames:

    def __init__(self):

        self.function_counter = 0
        self.constant_counter = 0

    def new_function(
        self,
        universal_variables
    ):

        self.function_counter += 1

        return Term(
            f"g{self.function_counter}",
            tuple(
                Term(
                    variable,
                    (),
                    True
                )
                for variable
                in universal_variables
            ),
            False
        )

    def new_constant(self):

        self.constant_counter += 1

        if self.constant_counter == 1:
            name = "c"

        else:
            name = (
                f"c{self.constant_counter}"
            )

        return Term(
            name,
            (),
            False
        )


def skolemize(
    f,
    names,
    universal_variables=(),
    explanations=None
):

    if explanations is None:
        explanations = []

    if isinstance(
        f,
        (Atom, Not)
    ):

        return f

    if isinstance(
        f,
        And
    ):

        return And(
            skolemize(
                f.a,
                names,
                universal_variables,
                explanations
            ),
            skolemize(
                f.b,
                names,
                universal_variables,
                explanations
            )
        )

    if isinstance(
        f,
        Or
    ):

        return Or(
            skolemize(
                f.a,
                names,
                universal_variables,
                explanations
            ),
            skolemize(
                f.b,
                names,
                universal_variables,
                explanations
            )
        )

    if isinstance(
        f,
        ForAll
    ):

        return ForAll(
            f.var,
            skolemize(
                f.body,
                names,
                universal_variables
                +
                (f.var,),
                explanations
            )
        )

    if isinstance(
        f,
        Exists
    ):

        if universal_variables:

            replacement = (
                names.new_function(
                    universal_variables
                )
            )

        else:

            replacement = (
                names.new_constant()
            )

        explanations.append(
            (
                f.var,
                replacement,
                universal_variables
            )
        )

        new_body = (
            substitute_formula(
                f.body,
                {
                    f.var:
                    replacement
                }
            )
        )

        return skolemize(
            new_body,
            names,
            universal_variables,
            explanations
        )

    raise TypeError(f)


