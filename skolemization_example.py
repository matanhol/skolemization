def prove(
    assumptions,
    conclusion,
    symmetric_relations=None,
    transitive_relations=None,
    reflexive_relations=None
):

    symmetric_relations = set(
        symmetric_relations
        or
        []
    )

    transitive_relations = set(
        transitive_relations
        or
        []
    )

    reflexive_relations = set(
        reflexive_relations
        or
        []
    )

    # ============================================================
    # ADD RELATION AXIOMS
    # ============================================================

    (
        extended_assumptions,
        generated_axioms
    ) = add_relation_axioms(
        assumptions,
        symmetric_relations,
        transitive_relations,
        reflexive_relations
    )

    print(
        "\n"
        + "=" * 70
    )

    print(
        "0. הוספת תכונות של יחסים ל-KB"
    )

    print(
        "=" * 70
    )

    if not generated_axioms:

        print(
            "\nלא הוגדרו תכונות מיוחדות של יחסים."
        )

    else:

        for (
            property_name,
            relation,
            axiom
        ) in generated_axioms:

            if (
                property_name
                ==
                "symmetric"
            ):

                description = (
                    "סימטרי"
                )

            elif (
                property_name
                ==
                "transitive"
            ):

                description = (
                    "טרנזיטיבי"
                )

            else:

                description = (
                    "רפלקסיבי"
                )

            print(
                f"\n{relation} הוגדר כיחס "
                f"{description}."
            )

            print(
                "מוסיפים ל-KB:"
            )

            print(
                f"    {axiom}"
            )

    print(
        "\nההנחות שאיתן נעבוד:"
    )

    for i, assumption in enumerate(
        extended_assumptions,
        1
    ):

        print(
            f"{i}. {assumption}"
        )

    print(
        "\nהמסקנה:"
    )

    print(
        conclusion
    )

    # ============================================================
    # PREPROCESS
    # ============================================================

    original_kb = (
        preprocess(
            extended_assumptions,
            conclusion
        )
    )

    # ============================================================
    # FOCUSED SEARCH
    # ============================================================

    if (
        FOCUS_ON_C
        and
        kb_contains_c(
            original_kb
        )
    ):

        focused_kb = (
            focus_kb_on_c(
                original_kb
            )
        )

        (
            status,
            final_kb
        ) = (
            run_resolution_search(
                focused_kb,
                "Resolution ממוקד ב-c"
            )
        )

        if (
            status
            ==
            "PROVED"
        ):

            print(
                "\n"
                + "=" * 70
            )

            print(
                "FINAL STATUS: PROVED"
            )

            print(
                "=" * 70
            )

            return (
                "PROVED"
            )

        if not FALLBACK_TO_GENERAL:

            print(
                "\nFINAL STATUS:",
                status
            )

            return status

        print(
            "\n"
            + "=" * 70
        )

        print(
            "החיפוש הממוקד הסתיים ללא הוכחה"
        )

        print(
            "=" * 70
        )

        print(
            "\nהמיקוד ב-c הוא heuristic בלבד."
        )

        print(
            "לכן חוזרים ל-KB המקורי "
            "ומנסים Resolution כללי."
        )

    # ============================================================
    # GENERAL SEARCH
    # ============================================================

    (
        status,
        final_kb
    ) = run_resolution_search(
        original_kb,
        "Resolution כללי"
    )

    print(
        "\n"
        + "=" * 70
    )

    print(
        "FINAL STATUS:",
        status
    )

    print(
        "=" * 70
    )

    return status

