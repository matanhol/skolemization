def add_relation_axioms(
    assumptions,
    symmetric_relations=None,
    transitive_relations=None,
    reflexive_relations=None
):

    symmetric_relations = set(
        symmetric_relations
        or
        []
    )

    transitive_relations = set(
        transitive_relations
        or
        []
    )

    reflexive_relations = set(
        reflexive_relations
        or
        []
    )

    result = list(
        assumptions
    )

    generated = []

    # ------------------------------------------------------------
    # Symmetry:
    #
    # ∀x∀y (R(x,y) -> R(y,x))
    # ------------------------------------------------------------

    for relation in sorted(
        symmetric_relations
    ):

        axiom = (
            f"all x all y "
            f"({relation}(x,y) -> "
            f"{relation}(y,x))"
        )

        result.append(
            axiom
        )

        generated.append(
            (
                "symmetric",
                relation,
                axiom
            )
        )

    # ------------------------------------------------------------
    # Transitivity:
    #
    # ∀x∀y∀z
    # ((R(x,y) and R(y,z)) -> R(x,z))
    # ------------------------------------------------------------

    for relation in sorted(
        transitive_relations
    ):

        axiom = (
            f"all x all y all z "
            f"(({relation}(x,y) and "
            f"{relation}(y,z)) -> "
            f"{relation}(x,z))"
        )

        result.append(
            axiom
        )

        generated.append(
            (
                "transitive",
                relation,
                axiom
            )
        )

    # ------------------------------------------------------------
    # Reflexivity:
    #
    # ∀x R(x,x)
    # ------------------------------------------------------------

    for relation in sorted(
        reflexive_relations
    ):

        axiom = (
            f"all x "
            f"{relation}(x,x)"
        )

        result.append(
            axiom
        )

        generated.append(
            (
                "reflexive",
                relation,
                axiom
            )
        )

    return (
        result,
        generated
    )


