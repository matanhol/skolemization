@dataclass(frozen=True)
class Term:
    name: str
    args: Tuple["Term", ...] = ()
    is_var: bool = False

    def __str__(self):

        shown_name = (
            visible_variable_name(self.name)
            if self.is_var
            else self.name
        )

        if self.args:

            return (
                f"{shown_name}("
                + ", ".join(
                    str(arg)
                    for arg in self.args
                )
                + ")"
            )

        return shown_name


