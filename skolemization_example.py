def flatten_or(f):

    if isinstance(
        f,
        Or
    ):

        return (
            flatten_or(
                f.a
            )
            +
            flatten_or(
                f.b
            )
        )

    if isinstance(
        f,
        Atom
    ):

        return [
            Literal(
                f,
                False
            )
        ]

    if (
        isinstance(
            f,
            Not
        )
        and
        isinstance(
            f.x,
            Atom
        )
    ):

        return [
            Literal(
                f.x,
                True
            )
        ]

    raise ValueError(
        "Expected clause, got: "
        + formula_str(f)
    )


