def to_nnf(
    f,
    negated=False
):

    if isinstance(
        f,
        Atom
    ):

        if negated:
            return Not(f)

        return f

    if isinstance(
        f,
        Not
    ):

        return to_nnf(
            f.x,
            not negated
        )

    if isinstance(
        f,
        And
    ):

        if negated:

            return Or(
                to_nnf(
                    f.a,
                    True
                ),
                to_nnf(
                    f.b,
                    True
                )
            )

        return And(
            to_nnf(
                f.a
            ),
            to_nnf(
                f.b
            )
        )

    if isinstance(
        f,
        Or
    ):

        if negated:

            return And(
                to_nnf(
                    f.a,
                    True
                ),
                to_nnf(
                    f.b,
                    True
                )
            )

        return Or(
            to_nnf(
                f.a
            ),
            to_nnf(
                f.b
            )
        )

    if isinstance(
        f,
        ForAll
    ):

        if negated:

            return Exists(
                f.var,
                to_nnf(
                    f.body,
                    True
                )
            )

        return ForAll(
            f.var,
            to_nnf(
                f.body
            )
        )

    if isinstance(
        f,
        Exists
    ):

        if negated:

            return ForAll(
                f.var,
                to_nnf(
                    f.body,
                    True
                )
            )

        return Exists(
            f.var,
            to_nnf(
                f.body
            )
        )

    raise TypeError(f)


