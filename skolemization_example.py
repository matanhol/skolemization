# HUMAN-READABLE SUBSTITUTIONS
# ================================================================

def meaningful_substitutions(
    substitution
):

    """
    Internal:
        __v230_x := g1(__v231_y)

    Visible:
        x := g1(y)

    Pure variable-to-variable bookkeeping is not printed.
    """

    result = []
    seen = set()

    for variable, value in substitution.items():

        final_value = (
            substitute_term(
                value,
                substitution
            )
        )

        # Don't show internal variable -> variable mappings.
        if final_value.is_var:
            continue

        shown_variable = (
            visible_variable_name(
                variable
            )
        )

        shown_value = str(
            final_value
        )

        key = (
            shown_variable,
            shown_value
        )

        if key in seen:
            continue

        seen.add(
            key
        )

        result.append(
            (
                shown_variable,
                shown_value
            )
        )

    return result


