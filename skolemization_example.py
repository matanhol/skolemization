def atom_str(atom):

    return (
        f"{atom.pred}("
        + ", ".join(
            str(arg)
            for arg in atom.args
        )
        + ")"
    )


def formula_str(f):

    if isinstance(f, Atom):
        return atom_str(f)

    if isinstance(f, Not):
        return "¬" + formula_str(f.x)

    if isinstance(f, And):
        return (
            f"({formula_str(f.a)} ∧ "
            f"{formula_str(f.b)})"
        )

    if isinstance(f, Or):
        return (
            f"({formula_str(f.a)} ∨ "
            f"{formula_str(f.b)})"
        )

    if isinstance(f, Implies):
        return (
            f"({formula_str(f.a)} → "
            f"{formula_str(f.b)})"
        )

    if isinstance(f, ForAll):
        return (
            f"∀{f.var} "
            f"{formula_str(f.body)}"
        )

    if isinstance(f, Exists):
        return (
            f"∃{f.var} "
            f"{formula_str(f.body)}"
        )

    raise TypeError(f)


def clause_str(clause):

    if len(clause) == 0:
        return "□"

    return " ∨ ".join(
        str(literal)
        for literal in clause
    )


