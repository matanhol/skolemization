def occurs(
    variable,
    term,
    substitution
):

    term = (
        substitute_term(
            term,
            substitution
        )
    )

    if term.is_var:

        return (
            term.name
            ==
            variable
        )

    return any(
        occurs(
            variable,
            arg,
            substitution
        )
        for arg
        in term.args
    )


def unify_variable(
    variable,
    term,
    substitution
):

    if variable in substitution:

        return unify_terms(
            substitution[
                variable
            ],
            term,
            substitution
        )

    if (
        term.is_var
        and
        term.name in substitution
    ):

        return unify_terms(
            Term(
                variable,
                (),
                True
            ),
            substitution[
                term.name
            ],
            substitution
        )

    if (
        term.is_var
        and
        term.name == variable
    ):

        return substitution

    if occurs(
        variable,
        term,
        substitution
    ):

        return None

    result = dict(
        substitution
    )

    result[
        variable
    ] = term

    return result


def unify_terms(
    a,
    b,
    substitution=None
):

    if substitution is None:
        substitution = {}

    a = substitute_term(
        a,
        substitution
    )

    b = substitute_term(
        b,
        substitution
    )

    if a == b:
        return substitution

    if a.is_var:

        return unify_variable(
            a.name,
            b,
            substitution
        )

    if b.is_var:

        return unify_variable(
            b.name,
            a,
            substitution
        )

    if (
        a.name != b.name
        or
        len(a.args)
        !=
        len(b.args)
    ):

        return None

    for x, y in zip(
        a.args,
        b.args
    ):

        substitution = (
            unify_terms(
                x,
                y,
                substitution
            )
        )

        if substitution is None:
            return None

    return substitution


def unify_atoms(
    a,
    b
):

    if (
        a.pred != b.pred
        or
        len(a.args)
        !=
        len(b.args)
    ):

        return None

    substitution = {}

    for x, y in zip(
        a.args,
        b.args
    ):

        substitution = (
            unify_terms(
                x,
                y,
                substitution
            )
        )

        if substitution is None:
            return None

    return substitution


def apply_substitution_literal(
    literal,
    substitution
):

    return Literal(
        Atom(
            literal.atom.pred,
            tuple(
                substitute_term(
                    arg,
                    substitution
                )
                for arg
                in literal.atom.args
            )
        ),
        literal.negated
    )


# ================================================================
# STANDARDIZE VARIABLES APART
#
# Internal only.
#
# These ugly names are NEVER shown because Term.__str__()
# converts them back to x, y, z...
# ================================================================

_fresh_counter = itertools.count()


def standardize_clause(
    clause
):

    prefix = (
        f"__v"
        f"{next(_fresh_counter)}_"
    )

    mapping = {}

    def rename_term(term):

        if term.is_var:

            if term.name not in mapping:

                original_name = (
                    visible_variable_name(
                        term.name
                    )
                )

                mapping[
                    term.name
                ] = Term(
                    prefix
                    + original_name,
                    (),
                    True
                )

            return mapping[
                term.name
            ]

        return Term(
            term.name,
            tuple(
                rename_term(
                    arg
                )
                for arg
                in term.args
            ),
            False
        )

    result = []

    for literal in clause:

        result.append(
            Literal(
                Atom(
                    literal.atom.pred,
                    tuple(
                        rename_term(
                            arg
                        )
                        for arg
                        in literal.atom.args
                    )
                ),
                literal.negated
            )
        )

    return result


# ================================================================
# CLEAN VARIABLES AFTER RESOLUTION
# ================================================================

def clean_clause_variables(
    clause
):

    """
    Convert surviving internal variables to clean names:

        x, y, z, u, v, w, x7, ...

    This is for storing the new clause in the visible KB.
    """

    mapping = {}

    preferred = [
        "x",
        "y",
        "z",
        "u",
        "v",
        "w"
    ]

    counter = 0

    def clean_term(term):

        nonlocal counter

        if term.is_var:

            if term.name not in mapping:

                original = (
                    visible_variable_name(
                        term.name
                    )
                )

                # Prefer original name if available and unused.
                used_names = {
                    t.name
                    for t
                    in mapping.values()
                }

                if (
                    original not in used_names
                    and
                    not original.startswith("__")
                ):

                    new_name = original

                elif counter < len(
                    preferred
                ):

                    while (
                        counter
                        <
                        len(preferred)
                        and
                        preferred[counter]
                        in used_names
                    ):
                        counter += 1

                    if counter < len(
                        preferred
                    ):

                        new_name = (
                            preferred[
                                counter
                            ]
                        )

                        counter += 1

                    else:

                        new_name = (
                            f"x{counter + 1}"
                        )

                        counter += 1

                else:

                    new_name = (
                        f"x{counter + 1}"
                    )

                    counter += 1

                mapping[
                    term.name
                ] = Term(
                    new_name,
                    (),
                    True
                )

            return mapping[
                term.name
            ]

        return Term(
            term.name,
            tuple(
                clean_term(
                    arg
                )
                for arg
                in term.args
            ),
            False
        )

    result = []

    for literal in clause:

        result.append(
            Literal(
                Atom(
                    literal.atom.pred,
                    tuple(
                        clean_term(
                            arg
                        )
                        for arg
                        in literal.atom.args
                    )
                ),
                literal.negated
            )
        )

    return result


# ================================================================
# CANONICAL REPRESENTATION
# ================================================================

def canonical_clause(
    clause
):

    """
    Alpha-equivalent clauses should count as the same clause.

    Example:
        P(x) ∨ Q(y)
        P(u) ∨ Q(v)

    are treated as identical.
    """

    mapping = {}
    counter = 0

    def canonical_term(term):

        nonlocal counter

        if term.is_var:

            if term.name not in mapping:

                counter += 1

                mapping[
                    term.name
                ] = (
                    f"V{counter}"
                )

            return mapping[
                term.name
            ]

        if term.args:

            return (
                term.name
                + "("
                + ",".join(
                    canonical_term(
                        arg
                    )
                    for arg
                    in term.args
                )
                + ")"
            )

        return term.name

    ordered_literals = sorted(
        clause,
        key=lambda literal: (
            literal.negated,
            literal.atom.pred,
            str(literal)
        )
    )

    result = []

    for literal in ordered_literals:

        sign = (
            "~"
            if literal.negated
            else "+"
        )

        result.append(
            sign
            + literal.atom.pred
            + "("
            + ",".join(
                canonical_term(
                    arg
                )
                for arg
                in literal.atom.args
            )
            + ")"
        )

    return tuple(
        sorted(result)
    )


# ================================================================
# TAUTOLOGY
# ================================================================

def clause_is_tautology(
    clause
):

    for i, first in enumerate(
        clause
    ):

        for j, second in enumerate(
            clause
        ):

            if i == j:
                continue

            if (
                first.negated
                !=
                second.negated
                and
                first.atom
                ==
                second.atom
            ):

                return True

    return False


# ================================================================
# RESOLUTION BETWEEN TWO CLAUSES
# ================================================================

def resolve_two_clauses(
    clause1,
    clause2
):

    left = (
        standardize_clause(
            clause1
        )
    )

    right = (
        standardize_clause(
            clause2
        )
    )

    possibilities = []

    for i, lit1 in enumerate(
        left
    ):

        for j, lit2 in enumerate(
            right
        ):

            if (
                lit1.negated
                ==
                lit2.negated
            ):

                continue

            substitution = (
                unify_atoms(
                    lit1.atom,
                    lit2.atom
                )
            )

            if substitution is None:
                continue

            resolvent = []

            for k, literal in enumerate(
                left
            ):

                if k != i:

                    resolvent.append(
                        apply_substitution_literal(
                            literal,
                            substitution
                        )
                    )

            for k, literal in enumerate(
                right
            ):

                if k != j:

                    resolvent.append(
                        apply_substitution_literal(
                            literal,
                            substitution
                        )
                    )

            unique = []

            for literal in resolvent:

                if literal not in unique:

                    unique.append(
                        literal
                    )

            if clause_is_tautology(
                unique
            ):

                continue

            clean_resolvent = (
                clean_clause_variables(
                    unique
                )
            )

            possibilities.append(
                (
                    lit1,
                    lit2,
                    substitution,
                    clean_resolvent
                )
            )

    return possibilities


