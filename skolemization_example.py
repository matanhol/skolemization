TOKEN_RE = re.compile(
    r"\s*(->|-->|∀|∃|¬|!|\?|~|\(|\)|,|:|&|\||"
    r"[A-Za-z_][A-Za-z0-9_]*)"
)


def tokenize(text):

    result = []

    for token in TOKEN_RE.findall(
        text
    ):

        low = token.lower()

        if low in (
            "all",
            "forall"
        ):
            result.append(
                "forall"
            )

        elif low == "exists":
            result.append(
                "exists"
            )

        elif low == "not":
            result.append(
                "not"
            )

        elif low == "and":
            result.append(
                "and"
            )

        elif low == "or":
            result.append(
                "or"
            )

        elif token in (
            "->",
            "-->"
        ):
            result.append(
                "->"
            )

        elif token in (
            "¬",
            "~"
        ):
            result.append(
                "not"
            )

        elif token in (
            "∀",
            "!"
        ):
            result.append(
                "forall"
            )

        elif token in (
            "∃",
            "?"
        ):
            result.append(
                "exists"
            )

        elif token == "&":
            result.append(
                "and"
            )

        elif token == "|":
            result.append(
                "or"
            )

        else:
            result.append(
                token
            )

    return result


class Parser:

    def __init__(
        self,
        text
    ):

        self.tokens = tokenize(
            text
        )

        self.i = 0

        self.bound_variables = []

    def peek(self):

        if self.i >= len(
            self.tokens
        ):
            return None

        return self.tokens[
            self.i
        ]

    def eat(
        self,
        expected=None
    ):

        token = self.peek()

        if token is None:

            raise SyntaxError(
                "Unexpected end of formula"
            )

        if (
            expected is not None
            and token != expected
        ):

            raise SyntaxError(
                f"Expected '{expected}', "
                f"found '{token}'"
            )

        self.i += 1

        return token

    def parse(self):

        result = (
            self.parse_implication()
        )

        if self.peek() is not None:

            raise SyntaxError(
                f"Unexpected token: "
                f"{self.peek()}"
            )

        return result

    def parse_implication(self):

        left = self.parse_or()

        if self.peek() == "->":

            self.eat(
                "->"
            )

            right = (
                self.parse_implication()
            )

            return Implies(
                left,
                right
            )

        return left

    def parse_or(self):

        left = self.parse_and()

        while self.peek() == "or":

            self.eat(
                "or"
            )

            left = Or(
                left,
                self.parse_and()
            )

        return left

    def parse_and(self):

        left = self.parse_unary()

        while self.peek() == "and":

            self.eat(
                "and"
            )

            left = And(
                left,
                self.parse_unary()
            )

        return left

    def parse_unary(self):

        token = self.peek()

        if token == "not":

            self.eat(
                "not"
            )

            return Not(
                self.parse_unary()
            )

        if token in (
            "forall",
            "exists"
        ):

            quantifier = (
                self.eat()
            )

            variable = (
                self.eat()
            )

            if self.peek() in (
                ",",
                ":"
            ):
                self.eat()

            old_bound = list(
                self.bound_variables
            )

            self.bound_variables.append(
                variable
            )

            body = (
                self.parse_implication()
            )

            self.bound_variables = (
                old_bound
            )

            if (
                quantifier
                ==
                "forall"
            ):

                return ForAll(
                    variable,
                    body
                )

            return Exists(
                variable,
                body
            )

        if token == "(":

            self.eat(
                "("
            )

            result = (
                self.parse_implication()
            )

            self.eat(
                ")"
            )

            return result

        return self.parse_atom()

    def parse_atom(self):

        predicate = self.eat()

        self.eat(
            "("
        )

        args = []

        if self.peek() != ")":

            while True:

                args.append(
                    self.parse_term()
                )

                if self.peek() == ",":

                    self.eat(
                        ","
                    )

                    continue

                break

        self.eat(
            ")"
        )

        return Atom(
            predicate,
            tuple(args)
        )

    def parse_term(self):

        name = self.eat()

        if self.peek() == "(":

            self.eat(
                "("
            )

            args = []

            if self.peek() != ")":

                while True:

                    args.append(
                        self.parse_term()
                    )

                    if self.peek() == ",":

                        self.eat(
                            ","
                        )

                        continue

                    break

            self.eat(
                ")"
            )

            return Term(
                name,
                tuple(args),
                False
            )

        return Term(
            name,
            (),
            name
            in
            self.bound_variables
        )


